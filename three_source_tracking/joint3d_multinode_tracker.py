#!/usr/bin/env python3
"""GPS-free multi-node fusion and fixed-cardinality tracking for Baoding.

Input candidates are joint 3-D MUSIC directions from every 19-microphone node.
Spatial hypotheses are generated by ray pairs, scored by all-node angular
consensus, grouped into non-overlapping three-source sets, and linked with a
constant-velocity beam search.  GPS is joined only after the winning acoustic
path is fixed.
"""
from __future__ import annotations

import argparse
import itertools
import json
import math
from pathlib import Path

import numpy as np

from summarize_three_source_raw_music_xyz import hhmmss_to_seconds, load_gps, load_nod


PERMS = tuple(itertools.permutations(range(3)))


def direction(azimuth_deg: float, zenith_deg: float) -> np.ndarray:
    az = math.radians(azimuth_deg)
    ze = math.radians(zenith_deg)
    return np.asarray([math.sin(ze) * math.cos(az), math.sin(ze) * math.sin(az), math.cos(ze)])


def angle_deg(first: np.ndarray, second: np.ndarray) -> float:
    return float(math.degrees(math.acos(float(np.clip(np.dot(first, second), -1.0, 1.0)))))


def pair_intersection(p1: np.ndarray, u1: np.ndarray, p2: np.ndarray, u2: np.ndarray):
    q1 = np.eye(3) - np.outer(u1, u1)
    q2 = np.eye(3) - np.outer(u2, u2)
    matrix = q1 + q2
    cond = float(np.linalg.cond(matrix))
    if not np.isfinite(cond) or cond > 2.0e4:
        return None
    point = np.linalg.lstsq(matrix, q1 @ p1 + q2 @ p2, rcond=None)[0]
    forward1 = float(np.dot(point - p1, u1))
    forward2 = float(np.dot(point - p2, u2))
    residual = 0.5 * (np.linalg.norm(q1 @ (point - p1)) + np.linalg.norm(q2 @ (point - p2)))
    return point, cond, float(residual), forward1, forward2


def candidate_arrays(frame_rows: dict[str, dict]) -> dict[str, dict]:
    result = {}
    for node, row in frame_rows.items():
        candidates = row["candidates"]
        vectors = np.asarray([direction(x["azimuth_deg"], x["zenith_deg"]) for x in candidates])
        raw_scores = np.asarray([float(x["score"]) for x in candidates])
        spread = max(float(np.std(raw_scores)), 1e-6)
        normalized = np.clip((raw_scores - float(np.median(raw_scores))) / spread, -3.0, 3.0)
        result[node] = {"vectors": vectors, "scores": normalized, "raw": candidates}
    return result


def score_point(point: np.ndarray, nodes: dict[str, np.ndarray], candidates: dict[str, dict]) -> dict:
    errors, indices, strengths = {}, {}, {}
    for node, node_position in nodes.items():
        delta = point - node_position
        distance = float(np.linalg.norm(delta))
        if distance < 1.0:
            return {"valid": False}
        expected = delta / distance
        values = [angle_deg(expected, vector) for vector in candidates[node]["vectors"]]
        index = int(np.argmin(values))
        errors[node] = float(values[index])
        indices[node] = index
        strengths[node] = float(candidates[node]["scores"][index])
    ordered = np.sort(np.asarray(list(errors.values())))
    within8 = int(np.sum(ordered <= 8.0))
    within15 = int(np.sum(ordered <= 15.0))
    if within8 < 3 or within15 < 4:
        return {"valid": False}
    # The four best nodes determine geometric consistency; the remaining
    # nodes add bounded support without allowing one bad array to veto a track.
    angular_cost = float(np.mean(np.minimum(ordered[:6], 25.0)))
    strength_bonus = float(np.mean(sorted(strengths.values(), reverse=True)[:4]))
    cost = angular_cost - 0.35 * strength_bonus - 0.8 * within8 - 0.25 * within15
    return {
        "valid": True,
        "cost": cost,
        "angular_cost_deg": angular_cost,
        "within8_nodes": within8,
        "within15_nodes": within15,
        "nearest_candidate_index": indices,
        "node_errors_deg": errors,
        "candidate_strength": strengths,
    }


def point_hypotheses(
    frame_rows: dict[str, dict],
    nodes: dict[str, np.ndarray],
    position_bound: float,
    min_height: float,
    max_height: float,
    max_pair_residual: float,
    nms_distance: float,
    keep: int,
) -> list[dict]:
    candidates = candidate_arrays(frame_rows)
    proposals = []
    node_names = list(nodes)
    for node_a, node_b in itertools.combinations(node_names, 2):
        p1, p2 = nodes[node_a], nodes[node_b]
        for index_a, u1 in enumerate(candidates[node_a]["vectors"]):
            for index_b, u2 in enumerate(candidates[node_b]["vectors"]):
                intersection = pair_intersection(p1, u1, p2, u2)
                if intersection is None:
                    continue
                point, cond, residual, forward1, forward2 = intersection
                if forward1 <= 0.0 or forward2 <= 0.0 or residual > max_pair_residual:
                    continue
                if np.linalg.norm(point[:2]) > position_bound or not (min_height <= point[2] <= max_height):
                    continue
                scored = score_point(point, nodes, candidates)
                if not scored.get("valid"):
                    continue
                scored.update({
                    "position": point,
                    "seed_nodes": [node_a, node_b],
                    "seed_candidate_index": [index_a, index_b],
                    "pair_condition": cond,
                    "pair_residual_m": residual,
                })
                proposals.append(scored)
    proposals.sort(key=lambda row: (row["cost"], -row["within8_nodes"], row["pair_residual_m"]))
    selected = []
    for row in proposals:
        if all(float(np.linalg.norm(row["position"] - other["position"])) >= nms_distance for other in selected):
            selected.append(row)
        if len(selected) >= keep:
            break
    return selected


def source_sets(points: list[dict], keep: int, min_separation: float, max_duplicate_nodes: int) -> list[dict]:
    sets = []
    for indices in itertools.combinations(range(len(points)), 3):
        chosen = [points[i] for i in indices]
        distances = [float(np.linalg.norm(chosen[a]["position"] - chosen[b]["position"])) for a, b in ((0, 1), (0, 2), (1, 2))]
        if min(distances) < min_separation:
            continue
        duplicate_nodes = 0
        for node in chosen[0]["nearest_candidate_index"]:
            used = [row["nearest_candidate_index"][node] for row in chosen]
            duplicate_nodes += int(len(set(used)) < 3)
        if duplicate_nodes > max_duplicate_nodes:
            continue
        coverage = sum(row["within8_nodes"] for row in chosen)
        cost = sum(row["cost"] for row in chosen) + 3.0 * duplicate_nodes - 0.15 * coverage
        sets.append({
            "indices": list(indices),
            "positions": np.asarray([row["position"] for row in chosen]),
            "measurement_cost": float(cost),
            "duplicate_nodes": duplicate_nodes,
            "coverage8_total": coverage,
        })
    sets.sort(key=lambda row: row["measurement_cost"])
    return sets[:keep]


def transition(previous: dict, current: dict, dt: float, position_sigma: float, acceleration_sigma: float, max_speed: float):
    predicted = previous["positions"] + previous["velocities"] * dt
    best = None
    for perm in PERMS:
        positions = current["positions"][list(perm)]
        innovation = positions - predicted
        velocities = (positions - previous["positions"]) / dt
        speed = np.linalg.norm(velocities, axis=1)
        if float(np.max(speed)) > max_speed:
            continue
        acceleration = (velocities - previous["velocities"]) / dt
        motion_cost = float(np.sum((np.linalg.norm(innovation, axis=1) / position_sigma) ** 2))
        if previous["age"] > 1:
            motion_cost += float(np.sum((np.linalg.norm(acceleration, axis=1) / acceleration_sigma) ** 2))
        if best is None or motion_cost < best[0]:
            best = (motion_cost, positions, velocities, perm)
    return best


def beam_track(
    sets_by_frame: list[list[dict]],
    dt: float,
    beam_width: int,
    position_sigma: float,
    acceleration_sigma: float,
    max_speed: float,
    measurement_weight: float,
    hold_penalty: float,
    max_consecutive_holds: int,
) -> dict:
    first = sets_by_frame[0]
    if not first:
        raise RuntimeError("no valid source set in first frame")
    base_cost = first[0]["measurement_cost"]
    beam = []
    for source_set in first:
        order = np.argsort(source_set["positions"][:, 0])
        beam.append({
            "score": measurement_weight * (source_set["measurement_cost"] - base_cost),
            "positions": source_set["positions"][order],
            "velocities": np.zeros((3, 3)),
            "age": 1,
            "consecutive_holds": 0,
            "updates": 1,
            "path": [source_set],
            "position_path": [source_set["positions"][order]],
        })
    beam = sorted(beam, key=lambda row: row["score"])[:beam_width]
    for frame_sets in sets_by_frame[1:]:
        if not frame_sets:
            raise RuntimeError("a frame has no valid three-source set")
        base_cost = frame_sets[0]["measurement_cost"]
        expanded = []
        for previous in beam:
            if previous["consecutive_holds"] < max_consecutive_holds:
                predicted = previous["positions"] + previous["velocities"] * dt
                expanded.append({
                    "score": previous["score"] + hold_penalty,
                    "positions": predicted,
                    "velocities": previous["velocities"],
                    "age": previous["age"] + 1,
                    "consecutive_holds": previous["consecutive_holds"] + 1,
                    "updates": previous["updates"],
                    "path": previous["path"] + [None],
                    "position_path": previous["position_path"] + [predicted],
                    "last_perm": None,
                })
            for source_set in frame_sets:
                moved = transition(previous, source_set, dt, position_sigma, acceleration_sigma, max_speed)
                if moved is None:
                    continue
                motion_cost, positions, velocities, perm = moved
                expanded.append({
                    "score": previous["score"] + motion_cost + measurement_weight * (source_set["measurement_cost"] - base_cost),
                    "positions": positions,
                    "velocities": velocities,
                    "age": previous["age"] + 1,
                    "consecutive_holds": 0,
                    "updates": previous["updates"] + 1,
                    "path": previous["path"] + [source_set],
                    "position_path": previous["position_path"] + [positions],
                    "last_perm": list(perm),
                })
        if not expanded:
            raise RuntimeError("beam search lost all tracks")
        beam = sorted(expanded, key=lambda row: row["score"])[:beam_width]
    return beam[0]


def beam_track_partial(
    points_by_frame: list[list[dict]],
    first_sets: list[dict],
    dt: float,
    beam_width: int,
    position_sigma: float,
    acceleration_sigma: float,
    max_speed: float,
    measurement_weight: float,
    hold_penalty: float,
    max_consecutive_holds: int,
    options_per_target: int,
    max_duplicate_nodes: int,
    min_source_separation: float,
    frame_labels: list[int] | None = None,
) -> dict:
    """Multi-hypothesis tracking with target-wise detections and misses."""
    first_base = first_sets[0]["measurement_cost"]
    beam = []
    for source_set in first_sets:
        order = np.argsort(source_set["positions"][:, 0])
        positions = source_set["positions"][order]
        beam.append({
            "score": measurement_weight * (source_set["measurement_cost"] - first_base),
            "positions": positions,
            "velocities": np.zeros((3, 3)),
            "age": 1,
            "consecutive_holds": np.zeros(3, dtype=int),
            "updates_by_target": np.ones(3, dtype=int),
            "path": [[int(source_set["indices"][x]) for x in order]],
            "position_path": [positions],
        })
    beam = sorted(beam, key=lambda row: row["score"])[:beam_width]

    diagnostics = []
    for frame_index, points in enumerate(points_by_frame[1:], start=1):
        frame_label = frame_labels[frame_index] if frame_labels is not None else frame_index
        if not points:
            raise RuntimeError(f"frame {frame_label} has no valid point hypotheses")
        point_positions = np.asarray([row["position"] for row in points])
        point_cost = np.asarray([float(row["cost"]) for row in points])
        point_cost = point_cost - float(np.min(point_cost))
        expanded = []
        rejected = {
            "beam_states_without_three_options": 0,
            "assignments_considered": 0,
            "candidate_reuse": 0,
            "duplicate_node_gate": 0,
            "source_separation_gate": 0,
        }
        option_counts = []
        for previous in beam:
            predicted = previous["positions"] + previous["velocities"] * dt
            options = []
            for target in range(3):
                distance_to_prediction = np.linalg.norm(point_positions - predicted[target], axis=1)
                speed = np.linalg.norm(point_positions - previous["positions"][target], axis=1) / dt
                preliminary = (distance_to_prediction / position_sigma) ** 2 + measurement_weight * point_cost
                valid = np.flatnonzero(speed <= max_speed)
                ranked = valid[np.argsort(preliminary[valid])[:options_per_target]].tolist()
                if previous["consecutive_holds"][target] < max_consecutive_holds:
                    ranked.append(None)
                options.append(ranked)
            option_counts.append([len(row) for row in options])
            if any(not row for row in options):
                rejected["beam_states_without_three_options"] += 1
                continue
            for assignment in itertools.product(*options):
                rejected["assignments_considered"] += 1
                measured = [index for index in assignment if index is not None]
                if len(measured) != len(set(measured)):
                    rejected["candidate_reuse"] += 1
                    continue
                duplicate_nodes = 0
                if len(measured) >= 2:
                    for node in points[measured[0]]["nearest_candidate_index"]:
                        used = [points[index]["nearest_candidate_index"][node] for index in measured]
                        duplicate_nodes += int(len(used) < len(measured))
                if duplicate_nodes > max_duplicate_nodes:
                    rejected["duplicate_node_gate"] += 1
                    continue
                positions = predicted.copy()
                velocities = previous["velocities"].copy()
                consecutive = previous["consecutive_holds"].copy()
                updates = previous["updates_by_target"].copy()
                score = float(previous["score"] + 3.0 * duplicate_nodes)
                for target, index in enumerate(assignment):
                    if index is None:
                        score += hold_penalty
                        consecutive[target] += 1
                        continue
                    positions[target] = point_positions[index]
                    velocity = (positions[target] - previous["positions"][target]) / dt
                    innovation = float(np.linalg.norm(positions[target] - predicted[target]))
                    acceleration = float(np.linalg.norm(velocity - previous["velocities"][target]) / dt)
                    score += (innovation / position_sigma) ** 2
                    if previous["age"] > 1:
                        score += (acceleration / acceleration_sigma) ** 2
                    score += measurement_weight * point_cost[index]
                    velocities[target] = velocity
                    consecutive[target] = 0
                    updates[target] += 1
                separations = [
                    float(np.linalg.norm(positions[a] - positions[b]))
                    for a, b in ((0, 1), (0, 2), (1, 2))
                ]
                if min(separations) < min_source_separation:
                    rejected["source_separation_gate"] += 1
                    continue
                expanded.append({
                    "score": score,
                    "positions": positions,
                    "velocities": velocities,
                    "age": previous["age"] + 1,
                    "consecutive_holds": consecutive,
                    "updates_by_target": updates,
                    "path": previous["path"] + [[None if x is None else int(x) for x in assignment]],
                    "position_path": previous["position_path"] + [positions],
                })
        frame_diagnostic = {
            "frame_index": frame_index,
            "frame_label": int(frame_label),
            "point_hypotheses": len(points),
            "beam_states_in": len(beam),
            "option_count_min": np.min(option_counts, axis=0).tolist() if option_counts else [0, 0, 0],
            "option_count_max": np.max(option_counts, axis=0).tolist() if option_counts else [0, 0, 0],
            **rejected,
            "expanded_states": len(expanded),
        }
        diagnostics.append(frame_diagnostic)
        if not expanded:
            raise RuntimeError(
                "partial-update beam search lost all tracks: "
                + json.dumps(frame_diagnostic, ensure_ascii=True, sort_keys=True)
            )
        beam = sorted(expanded, key=lambda row: row["score"])[:beam_width]
    winner = beam[0]
    winner["tracking_diagnostics"] = diagnostics
    return winner


def measurement_std(
    point: dict,
    nodes: dict[str, np.ndarray],
    angular_scale: float,
    minimum: float,
    maximum: float,
) -> float:
    position = np.asarray(point["position"], dtype=float)
    median_range = float(np.median([np.linalg.norm(position - node) for node in nodes.values()]))
    angular = math.radians(max(float(point.get("angular_cost_deg", 5.0)), 0.5))
    residual = float(point.get("pair_residual_m", 0.0))
    value = angular_scale * median_range * math.sin(angular) + residual
    return float(np.clip(value, minimum, maximum))


def kalman_rts_smooth(
    raw_positions: np.ndarray,
    association_path: list[list[int | None]],
    points_by_frame: list[list[dict]],
    nodes: dict[str, np.ndarray],
    dt: float,
    acceleration_std: float,
    initial_position_std: float,
    initial_velocity_std: float,
    angular_scale: float,
    minimum_measurement_std: float,
    maximum_measurement_std: float,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Run independent 6-D CV Kalman filters followed by RTS smoothing."""
    frame_count, target_count, _ = raw_positions.shape
    transition_matrix = np.eye(6)
    transition_matrix[:3, 3:] = np.eye(3) * dt
    observation_matrix = np.zeros((3, 6))
    observation_matrix[:, :3] = np.eye(3)
    acceleration_map = np.vstack([0.5 * dt * dt * np.eye(3), dt * np.eye(3)])
    process_covariance = acceleration_std**2 * acceleration_map @ acceleration_map.T
    identity = np.eye(6)

    states = np.zeros((frame_count, target_count, 6))
    covariances = np.zeros((frame_count, target_count, 6, 6))
    sigmas = np.full((frame_count, target_count), np.nan)
    for frame_index, assignments in enumerate(association_path):
        for target, point_index in enumerate(assignments):
            if point_index is not None:
                sigmas[frame_index, target] = measurement_std(
                    points_by_frame[frame_index][point_index], nodes, angular_scale,
                    minimum_measurement_std, maximum_measurement_std,
                )

    for target in range(target_count):
        filtered_state = np.zeros((frame_count, 6))
        filtered_covariance = np.zeros((frame_count, 6, 6))
        predicted_state = np.zeros((frame_count, 6))
        predicted_covariance = np.zeros((frame_count, 6, 6))
        filtered_state[0, :3] = raw_positions[0, target]
        filtered_covariance[0] = np.diag(
            [initial_position_std**2] * 3 + [initial_velocity_std**2] * 3
        )
        predicted_state[0] = filtered_state[0]
        predicted_covariance[0] = filtered_covariance[0]

        for frame_index in range(1, frame_count):
            predicted_state[frame_index] = transition_matrix @ filtered_state[frame_index - 1]
            predicted_covariance[frame_index] = (
                transition_matrix @ filtered_covariance[frame_index - 1] @ transition_matrix.T
                + process_covariance
            )
            filtered_state[frame_index] = predicted_state[frame_index]
            filtered_covariance[frame_index] = predicted_covariance[frame_index]
            if association_path[frame_index][target] is None:
                continue
            variance = sigmas[frame_index, target] ** 2
            measurement_covariance = np.eye(3) * variance
            innovation_covariance = (
                observation_matrix @ predicted_covariance[frame_index] @ observation_matrix.T
                + measurement_covariance
            )
            gain = (
                predicted_covariance[frame_index] @ observation_matrix.T
                @ np.linalg.inv(innovation_covariance)
            )
            innovation = raw_positions[frame_index, target] - observation_matrix @ predicted_state[frame_index]
            filtered_state[frame_index] += gain @ innovation
            update = identity - gain @ observation_matrix
            filtered_covariance[frame_index] = (
                update @ predicted_covariance[frame_index] @ update.T
                + gain @ measurement_covariance @ gain.T
            )

        smoothed_state = filtered_state.copy()
        smoothed_covariance = filtered_covariance.copy()
        for frame_index in range(frame_count - 2, -1, -1):
            smoother_gain = (
                filtered_covariance[frame_index] @ transition_matrix.T
                @ np.linalg.inv(predicted_covariance[frame_index + 1])
            )
            smoothed_state[frame_index] += smoother_gain @ (
                smoothed_state[frame_index + 1] - predicted_state[frame_index + 1]
            )
            smoothed_covariance[frame_index] += smoother_gain @ (
                smoothed_covariance[frame_index + 1] - predicted_covariance[frame_index + 1]
            ) @ smoother_gain.T
            smoothed_covariance[frame_index] = 0.5 * (
                smoothed_covariance[frame_index] + smoothed_covariance[frame_index].T
            )
        states[:, target] = smoothed_state
        covariances[:, target] = smoothed_covariance
    return states, covariances, sigmas


def nearest_gps(track: tuple[np.ndarray, np.ndarray], time_s: float) -> np.ndarray:
    xyz, times = track
    return xyz[int(np.argmin(np.abs(times - time_s)))]


def evaluate(path: np.ndarray, times: list[float], gps: list[tuple[np.ndarray, np.ndarray]], origin: np.ndarray) -> dict:
    truth = np.asarray([[nearest_gps(track, t) - origin for track in gps] for t in times])
    best = None
    for perm in PERMS:
        error = np.linalg.norm(path - truth[:, list(perm), :], axis=2)
        rmse = float(np.sqrt(np.mean(error ** 2)))
        if best is None or rmse < best[0]:
            best = (rmse, perm, error)
    assert best is not None
    error = best[2]
    optimal_frame = []
    for frame_index in range(len(times)):
        value = min(float(np.mean(np.linalg.norm(path[frame_index] - truth[frame_index, list(perm), :], axis=1))) for perm in PERMS)
        optimal_frame.append(value)
    return {
        "global_identity_assignment": list(best[1]),
        "fixed_identity_rmse_m": best[0],
        "target_rmse_m": [float(np.sqrt(np.mean(error[:, target] ** 2))) for target in range(3)],
        "target_mean_error_m": [float(np.mean(error[:, target])) for target in range(3)],
        "fixed_identity_mean_error_m": float(np.mean(error)),
        "fixed_identity_p90_error_m": float(np.quantile(error, 0.9)),
        "optimal_assignment_mean_error_m": float(np.mean(optimal_frame)),
        "optimal_assignment_p90_error_m": float(np.quantile(optimal_frame, 0.9)),
        "within_150m_fraction": float(np.mean(error <= 150.0)),
        "truth": truth.tolist(),
        "error_m": error.tolist(),
    }


def serializable_point(row: dict) -> dict:
    return {key: (value.tolist() if isinstance(value, np.ndarray) else value) for key, value in row.items()}


def normalized_time(value: float) -> float:
    """Accept new seconds-of-day caches and legacy HHMMSS.sss caches."""
    return float(hhmmss_to_seconds(value)) if value > 86400.0 else float(value)


